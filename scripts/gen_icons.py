"""Generates the launcher icon variants (one activity-alias each) and their Kotlin table.

Run from the repository root after changing the colours below:  python3 scripts/gen_icons.py
"""
import re

RES = 'app/src/main/res'
MANIFEST = 'app/src/main/AndroidManifest.xml'
KOTLIN = 'app/src/main/java/io/github/christiandonatti/fwip/ui/AppIconTable.kt'

# id, background, balloon, arrow
THEMES = [
    ('amber', '#F2B544', '#F2F2F5', '#0B0C10'),
    ('night', '#16171E', '#F2B544', '#16171E'),
    ('paper', '#F1E7D3', '#2A2118', '#F1E7D3'),
    ('oled', '#000000', '#4FD8E8', '#000000'),
    ('comic', '#1C2C74', '#FFD23F', '#1C2C74'),
    ('manga', '#F6F5F1', '#D7263D', '#F6F5F1'),
]
# Every highlight colour any theme offers (see ThemePreset.accents).
ACCENTS = ['#F2B544', '#6AA8FF', '#FF7A6B', '#5DD39E', '#B394FF', '#FF86BC',
           '#B8452B', '#2F5C8A', '#4F7A3A', '#A8741A', '#86304A',
           '#4FD8E8', '#B6F04A', '#FF5FC8',
           '#FFD23F', '#E63946', '#3EC1D3', '#FF8C42',
           '#D7263D', '#3A4BA0', '#2B2B2B']


def lum(hex_):
    r, g, b = (int(hex_[i:i + 2], 16) / 255 for i in (1, 3, 5))
    f = lambda c: c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


variants = list(THEMES)
for a in ACCENTS:
    light = lum(a) > 0.5
    balloon = '#16130C' if light else '#F2F2F5'
    arrow = a if light else ('#0B0C10' if lum(a) > 0.3 else a)
    variants.append(('a_' + a[1:].lower(), a, balloon, arrow))

FG = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateX="18" android:translateY="18">
        <path android:fillColor="{balloon}" android:pathData="M36,13 C50,13 60,21 60,31 C60,41 50,49 36,49 C33,49 30,48.6 27.4,47.9 L17,56 L19.5,45.2 C14.8,41.8 12,36.7 12,31 C12,21 22,13 36,13 Z" />
        <path android:strokeColor="{arrow}" android:strokeWidth="3.4" android:strokeLineCap="round" android:pathData="M25,33 C25,25 31,21 37,22 C42,23 46,27 46,31" />
        <path android:strokeColor="{arrow}" android:strokeWidth="3.4" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="M41.5,29.5 L46,32.5 L49,27.8" />
    </group>
</vector>
'''
ICON = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen_icons.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/icon_bg_{id}" />
    <foreground android:drawable="@drawable/ic_launcher_fg_{id}" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
colors = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by scripts/gen_icons.py -->', '<resources>']
aliases = []
for vid, bg, balloon, arrow in variants:
    open(f'{RES}/drawable/ic_launcher_fg_{vid}.xml', 'w').write(FG.format(balloon=balloon, arrow=arrow))
    open(f'{RES}/mipmap-anydpi-v26/ic_launcher_{vid}.xml', 'w').write(ICON.format(id=vid))
    colors.append(f'    <color name="icon_bg_{vid}">{bg}</color>')
    enabled = 'true' if vid == 'amber' else 'false'
    aliases.append(f'''        <activity-alias
            android:name=".Icon_{vid}"
            android:targetActivity=".MainActivity"
            android:exported="true"
            android:enabled="{enabled}"
            android:icon="@mipmap/ic_launcher_{vid}"
            android:roundIcon="@mipmap/ic_launcher_{vid}">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>''')
colors.append('</resources>')
open(f'{RES}/values/icon_colors.xml', 'w').write('\n'.join(colors) + '\n')

m = open(MANIFEST).read()
block = '        <!-- Launcher icons (generated by scripts/gen_icons.py): exactly one is enabled. -->\n' + '\n'.join(aliases) + '\n        <!-- /Launcher icons -->\n'
if '<!-- Launcher icons' in m:
    m = re.sub(r'        <!-- Launcher icons.*?<!-- /Launcher icons -->\n', lambda _: block, m, flags=re.S)
else:
    m = m.replace('        <receiver', block + '\n        <receiver', 1)
open(MANIFEST, 'w').write(m)

rows = ',\n'.join(f'    IconVariant("{vid}", 0xFF{bg[1:]}, 0xFF{balloon[1:]}, 0xFF{arrow[1:]})' for vid, bg, balloon, arrow in variants)
open(KOTLIN, 'w').write(f'''package io.github.christiandonatti.fwip.ui

// Generated by scripts/gen_icons.py: one launcher alias per entry.

/** A launcher icon: its alias id and the colours of background, balloon and arrow. */
class IconVariant(val id: String, bg: Long, balloon: Long, arrow: Long) {{
    val bg = bg.toInt()
    val balloon = balloon.toInt()
    val arrow = arrow.toInt()
}}

val ICON_VARIANTS = listOf(
{rows},
)
''')
print(len(variants), 'variants')
